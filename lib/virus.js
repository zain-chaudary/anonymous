'use strict';
/**
 * virus.js — the simulated intruder.
 *
 * READ THIS FIRST: none of this is malware. Every "executable" below is a
 * text file, every target is a folder inside ./sandbox, nothing touches the
 * host OS, nothing opens a socket, nothing sets real persistence, and the
 * whole thing is driven by explicit button clicks — it cannot self-start.
 *
 * What it *does* reproduce faithfully is the behaviour chain that defenders
 * actually have to detect: initial execution, run-key persistence, file
 * infection, removable-media spread and a destructive payload stage. Being
 * able to watch that chain and then watch a scanner dismantle it is the most
 * useful thing a simulation can teach.
 */

const crypto = require('node:crypto');

const FAMILY = 'Worm.Sim/7';
const MARKER = 'WORM::SIM-7';
const RANSOM_NOTE = 'C/Users/guest/Desktop/READ_ME_TO_RECOVER.txt';

/** Stage 1 payload. Fixed bytes so the signature database can hash it. */
const DELIVERY_CONTENT = [
  'MZ-SIMULATED-PAYLOAD',
  '; ---------------------------------------------------------------------',
  '; This is NOT an executable. It is a plain-text placeholder file used by',
  '; the Malware & Vaccine Lab to demonstrate how a file infector behaves.',
  '; Family: Worm.Sim/7   Build: 7.2.1   (simulation only)',
  '; If you are seeing this outside ./sandbox, something is very wrong.',
  '; ---------------------------------------------------------------------',
  '; Capabilities modelled: run-key persistence, document infection,',
  '; removable-media spread, extension hijack, destructive payload.',
  '; Capabilities deliberately NOT implemented: anything that could run.',
  '',
].join('\n');

const DELIVERY_PATH = 'C/Users/guest/Downloads/Invoice_2026-04.pdf.exe';
const HIDDEN_PATH = 'C/Users/guest/AppData/Roaming/svch0st.exe';

const AUTHORUN_INF = [
  '[AutoRun]',
  '; SIMULATION — this file is inert, it is a text file inside ./sandbox',
  'open=svch0st.exe',
  'action=Open folder to view files',
  'icon=svch0st.exe',
  '',
].join('\n');

const infectionBlock = (id) =>
  `\n--- SIMULATED-INFECTION: ${MARKER} (id=${id}) ---\n` +
  '--- this line is the detection signature; the vaccine strips it ---\n';

const ransomBody = (original, id) => {
  const blob = crypto.createHash('sha256').update(original + id).digest('hex');
  return [
    '-----BEGIN SIMULATED-ENCRYPTED BLOB-----',
    blob,
    blob.split('').reverse().join(''),
    '-----END SIMULATED-ENCRYPTED BLOB-----',
    '',
    'These bytes are not recoverable by decryption in this lab.',
    'That is the lesson: without a backup, this file is gone.',
    '',
  ].join('\n');
};

const noteBody = (id) => [
  'YOUR FILES HAVE BEEN (SIMULATED) ENCRYPTED',
  '',
  `Incident id: ${id}`,
  '',
  'This is a demo note generated by Malware & Vaccine Lab.',
  'In this simulation there is no decryption key — because real ransomware',
  'usually does not give you a working one either.',
  '',
  'What actually saves you: an offline backup you tested, and an',
  'incident response plan you rehearsed. Not the payment.',
  '',
].join('\n');

/**
 * The behaviour chain. Each stage is additive and idempotent-ish, so the lab
 * can be stepped one stage at a time and narrated.
 */
const STAGES = [
  {
    id: 1,
    title: 'Initial execution',
    blurb: 'A double-extension file in Downloads gets run by the user.',
    async run(ctx) {
      await ctx.write(DELIVERY_PATH, DELIVERY_CONTENT, { actor: 'virus' });
      ctx.log('info', `[virus] delivered ${DELIVERY_PATH}`);
      ctx.log('warn', '[virus] user opened "Invoice_2026-04.pdf" and got a .exe — double extension');
      return 'Execution + delivery complete';
    },
  },
  {
    id: 2,
    title: 'Persistence',
    blurb: 'Copies itself somewhere trusted and registers to run at logon.',
    async run(ctx) {
      let copyBlocked = false;
      if (await ctx.exists(DELIVERY_PATH)) {
        copyBlocked = !!(await ctx.move(DELIVERY_PATH, HIDDEN_PATH, { actor: 'virus' })).blocked;
      } else {
        copyBlocked = !!(await ctx.write(HIDDEN_PATH, DELIVERY_CONTENT, { actor: 'virus' })).blocked;
      }
      const keyBlocked = !!(await ctx.registry.add({
        name: 'SystemHealthMonitor',
        path: HIDDEN_PATH,
        publisher: 'unknown',
        trusted: false,
        source: 'HKCU\\...\\Run',
      })).blocked;
      const taskBlocked = !!(await ctx.registry.addTask({
        name: 'MsEdgeUpdateTaskSIM7',
        trigger: 'at logon',
        action: HIDDEN_PATH,
      })).blocked;

      if (!keyBlocked) ctx.log('warn', `[virus] persistence: run key "SystemHealthMonitor" -> ${HIDDEN_PATH}`);
      if (!taskBlocked) ctx.log('warn', '[virus] persistence: scheduled task "MsEdgeUpdateTaskSIM7" at logon');

      if (copyBlocked || (keyBlocked && taskBlocked)) {
        ctx.log('info', '[virus] persistence stage defeated — no foothold established');
        return 'Blocked: no persistence installed';
      }
      return 'Persistence installed';
    },
  },
  {
    id: 3,
    title: 'File infection',
    blurb: 'Appends its marker to every document it can reach, then clones itself.',
    async run(ctx) {
      const id = crypto.randomBytes(4).toString('hex');
      const files = await ctx.walk('C/Users/guest');
      let infected = 0;
      let refused = 0;
      for (const file of files) {
        if (file.endsWith('.exe') || file.endsWith('.json')) continue;
        if (file.includes('/AppData/Roaming/prefs')) continue;
        const body = await ctx.read(file);
        if (!body || body.includes(MARKER)) continue;
        const res = await ctx.write(file, body + infectionBlock(id), { actor: 'virus' });
        if (res.blocked) refused += 1;
        else infected += 1;
      }
      // Drop a clone next to the documents (classic file-infector habit).
      const dropped = [];
      for (const dir of new Set(files.map((f) => f.slice(0, f.lastIndexOf('/'))))) {
        const target = `${dir}/svch0st.exe`;
        if (target === HIDDEN_PATH) continue;
        const res = await ctx.write(target, DELIVERY_CONTENT + infectionBlock(id), { actor: 'virus' });
        if (!res.blocked) dropped.push(target);
        else refused += 1;
      }
      if (!infected && !dropped.length) {
        ctx.log('info', '[virus] infection stage defeated — every write was refused on access');
        return `Blocked: ${refused} write(s) refused, 0 documents infected`;
      }
      ctx.log('error', `[virus] infected ${infected} document(s); cloned itself into ${dropped.length} folder(s)`);
      if (refused) ctx.log('shield', `[vaccine] refused ${refused} malicious write(s) during this stage`);
      return `${infected} documents infected, ${dropped.length} clones dropped, ${refused} blocked`;
    },
  },
  {
    id: 4,
    title: 'Removable media spread',
    blurb: 'Writes itself plus an autorun.inf to the plugged-in USB stick.',
    async run(ctx) {
      const a = await ctx.write('D/removable/svch0st.exe', DELIVERY_CONTENT, { actor: 'virus' });
      const b = await ctx.write('D/removable/autorun.inf', AUTHORUN_INF, { actor: 'virus' });
      if (a.blocked && b.blocked) {
        ctx.log('info', '[virus] USB spread defeated — removable media is write-protected by the vaccine');
        return 'Blocked: USB stick stayed clean';
      }
      ctx.log('error', '[virus] copied itself to D:\\removable and wrote autorun.inf — USB propagation');
      return 'USB stick contaminated';
    },
  },
  {
    id: 5,
    title: 'Destructive payload',
    blurb: 'Overwrites files and renames them to .locked — the ransomware stage.',
    async run(ctx) {
      const id = crypto.randomBytes(4).toString('hex');
      const targets = [
        'C/Users/guest/Pictures/holiday-2025.txt',
        'C/Users/guest/Documents/thesis-draft.txt',
      ];
      let hit = 0;
      for (const target of targets) {
        const body = await ctx.read(target).catch(() => null);
        if (!body) continue;
        const res = await ctx.write(`${target}.locked`, ransomBody(body, id), { actor: 'virus' });
        if (res.blocked) continue;
        await ctx.remove(target, { actor: 'virus' });
        hit += 1;
      }
      await ctx.write(RANSOM_NOTE, noteBody(id), { actor: 'virus' });
      ctx.log('error', `[virus] payload stage: ${hit} file(s) replaced with .locked blobs`);
      ctx.log('error', '[virus] ransom note dropped on the Desktop');
      return `${hit} files destroyed`;
    },
  },
];

module.exports = {
  FAMILY,
  MARKER,
  DELIVERY_CONTENT,
  DELIVERY_PATH,
  HIDDEN_PATH,
  AUTHORUN_INF,
  RANSOM_NOTE,
  STAGES,
  infectionBlock,
};
